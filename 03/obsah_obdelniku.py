#OBSAH OBDÉLNÍKU
#Zkus napsat funkci, která vrátí obsah obdélníka daných rozměrů.
#Příslušný vzoreček je S = a×b, kde a a b jsou délky stran.


def obsah_obdelniku(strana1, strana2):
    """Funkce vezme délku stran a vypočítá obsah obdélníku."""
    return strana1 * strana2

print(obsah_obdelniku(2,4))
print(obsah_obdelniku(8,6))
